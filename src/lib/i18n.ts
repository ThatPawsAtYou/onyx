export function detectInitialLang(): Lang {
  try {
    const saved = window.localStorage.getItem('onyx-lang');
    if (saved === 'en' || saved === 'ru') return saved;
  } catch {
    // Ignore localStorage restrictions
  }
  return 'en';
}

